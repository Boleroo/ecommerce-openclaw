"""Generate OpenClaw TypeScript tool metadata from the Dispatcher registry."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "openclaw-plugin" / "src" / "registry.generated.ts"
sys.path.insert(0, str(ROOT))

from dispatcher.registry import REGISTRY  # noqa: E402


def agent_input_schema(tool):
    schema = tool.input_model.model_json_schema()
    # Phase 4's audit identified duplicate risk for unkeyed direct writes. The
    # backend remains backward compatible, but Agent-originated financial writes
    # must always carry a stable caller-supplied operation identity.
    if tool.name in {"refund_order", "change_price"}:
        key_schema = schema["properties"]["idempotency_key"]
        non_null = next(
            option for option in key_schema.pop("anyOf") if option.get("type") != "null"
        )
        key_schema.update(non_null)
        key_schema.pop("default", None)
        key_schema["description"] = (
            "Stable operation key. Reuse exactly the same key only when reconciling "
            "the same user-authorized write; never generate a new key for an unknown outcome."
        )
        schema.setdefault("required", []).append("idempotency_key")
    return schema


def main() -> None:
    entries = []
    for tool in REGISTRY.tools.values():
        if tool.endpoint.endswith(("/approve", "/reject")):
            raise RuntimeError(f"Human approval action must not be an Agent tool: {tool.name}")
        entries.append(
            {
                "name": tool.name,
                "description": tool.description,
                "parameters": agent_input_schema(tool),
                "method": tool.method,
                "optional": tool.method != "GET",
            }
        )
    rendered = (
        "// Generated by scripts/generate_openclaw_tools.py; do not edit manually.\n"
        "export const dispatcherTools = "
        + json.dumps(entries, indent=2, ensure_ascii=False)
        + " as const;\n"
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
